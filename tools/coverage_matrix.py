#!/usr/bin/env python3
"""Target-by-capability coverage matrix (docs/compatibility-matrix.json).

The JSON file is the source of truth. This tool validates it, prints the
coverage and depth scores, and renders the Markdown table in
docs/COMPATIBILITY.md between the coverage-matrix markers.

  tools/coverage_matrix.py              # validate and print scores
  tools/coverage_matrix.py --write      # also regenerate the Markdown table
  tools/coverage_matrix.py --check      # fail if the table is out of date
  tools/coverage_matrix.py --set TARGET CAP STATE "evidence or reason"
"""
import argparse
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
MATRIX = ROOT / "docs" / "compatibility-matrix.json"
DOC = ROOT / "docs" / "COMPATIBILITY.md"
BEGIN = "<!-- coverage-matrix:begin (generated by tools/coverage_matrix.py --write; do not edit) -->"
END = "<!-- coverage-matrix:end -->"
STATES = {"-": "no live evidence", "B": "basic", "V": "verified", "X": "blocked", "n/a": "not applicable"}


def load():
    return json.loads(MATRIX.read_text())


def validate(matrix):
    errors = []
    capabilities = [c["id"] for c in matrix["capabilities"]]
    seen = set()
    for target in matrix["targets"]:
        tid = target["id"]
        if tid in seen:
            errors.append(f"duplicate target {tid}")
        seen.add(tid)
        cells = target["cells"]
        if sorted(cells) != sorted(capabilities):
            errors.append(f"{tid}: cells must be exactly {capabilities}")
        for cap, cell in cells.items():
            state = cell.get("state")
            if state not in STATES:
                errors.append(f"{tid}/{cap}: invalid state {state!r}")
            elif state != "-" and not cell.get("evidence", "").strip():
                errors.append(f"{tid}/{cap}: state {state} needs evidence or a reason")
    return errors


def scores(matrix):
    applicable = covered = verified = 0
    for target in matrix["targets"]:
        for cell in target["cells"].values():
            if cell["state"] == "n/a":
                continue
            applicable += 1
            covered += cell["state"] in ("B", "V", "X")
            verified += cell["state"] == "V"
    return applicable, covered, verified


def render(matrix):
    capabilities = matrix["capabilities"]
    applicable, covered, verified = scores(matrix)
    lines = [BEGIN, ""]
    lines.append(f"**Coverage {covered}/{applicable} ({100 * covered / applicable:.0f}%)**, "
                 f"**depth {verified}/{applicable} ({100 * verified / applicable:.0f}%)**. "
                 "Coverage counts cells at `B`, `V` or `X`; depth counts `V`.")
    lines.append("")
    lines.append("| Target | " + " | ".join(c["id"] for c in capabilities) + " |")
    lines.append("|---|" + "---|" * len(capabilities))
    group = None
    for target in matrix["targets"]:
        if target["group"] != group:
            group = target["group"]
            lines.append(f"| **{group}** |" + " |" * len(capabilities))
        row = [target["cells"][c["id"]]["state"] for c in capabilities]
        lines.append(f"| {target['name']} | " + " | ".join(f"`{s}`" if s != "-" else "-" for s in row) + " |")
    lines.append("")
    lines.append("Capabilities: " + "; ".join(f"{c['id']} {c['name']}" for c in capabilities) + ".")
    lines.append("States: " + ", ".join(f"`{k}` {v}" for k, v in STATES.items()) +
                 ". Evidence and reasons for every cell are in "
                 "[compatibility-matrix.json](compatibility-matrix.json).")
    lines.append("")
    lines.append(END)
    return "\n".join(lines)


def replace_section(text, section):
    start, end = text.find(BEGIN), text.find(END)
    if start < 0 or end < start:
        raise SystemExit(f"{DOC.name}: coverage-matrix markers not found")
    return text[:start] + section + text[end + len(END):]


def main():
    parser = argparse.ArgumentParser()
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--set", nargs=4, metavar=("TARGET", "CAP", "STATE", "EVIDENCE"))
    args = parser.parse_args()
    matrix = load()
    if args.set:
        tid, cap, state, evidence = args.set
        target = next((t for t in matrix["targets"] if t["id"] == tid), None)
        if target is None or cap not in target["cells"]:
            raise SystemExit(f"unknown cell {tid}/{cap}")
        target["cells"][cap] = {"state": state, "evidence": evidence}
    errors = validate(matrix)
    if errors:
        print("\n".join(errors), file=sys.stderr)
        return 1
    if args.set:
        MATRIX.write_text(json.dumps(matrix, indent=1, ensure_ascii=False) + "\n")
    applicable, covered, verified = scores(matrix)
    print(f"coverage {covered}/{applicable} ({100 * covered / applicable:.1f}%), "
          f"depth {verified}/{applicable} ({100 * verified / applicable:.1f}%)")
    text = DOC.read_text()
    updated = replace_section(text, render(matrix))
    if args.check and updated != text:
        print(f"{DOC.name} coverage table is out of date: run tools/coverage_matrix.py --write", file=sys.stderr)
        return 1
    if (args.write or args.set) and updated != text:
        DOC.write_text(updated)
    return 0


if __name__ == "__main__":
    sys.exit(main())
